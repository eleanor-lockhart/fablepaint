def sec(i): return i / FPS
def beats(i): return i / BEAT
def lerp(a, b, t): return a + (b - a) * t
def clamp01(t): return min(max(t, 0.0), 1.0)

# ------------------------------------------------------------------ grounds
_SKY = {}
def sky(stops=NIGHT):
    """The night gradient, top to bottom. Returns a fresh copy."""
    if stops not in _SKY:
        _SKY[stops] = draw.gradient(W, H, (0, 0), (0, H), *stops)
    return _SKY[stops].copy()

def black(): return core.canvas(W, H, '#05070c')

def harbour(hz=430, moon=None, skyline=True, road=True, seed=0, shimmer=0, water=('#4b6274', '#2c4155', '#101a28')):
    """The Sound at night: sky, an optional moon (x, y, r), a far shore with a few warm windows, water below `hz`,
    and the moon's path on the water. `shimmer` reseeds the moving dashes: pass (pose // 2) so the water twinkles on twos."""
    img = sky()
    if moon:
        img = light(img, draw.disc(W, H, moon[0], moon[1], moon[2]), '#efe6cc', 2.2)
    if skyline:
        r = np.random.default_rng(seed); pts, x = [(-10, hz + 2)], -10.0
        while x < W + 20:
            wd = r.uniform(10, 30); hgt = 5 + r.uniform(0, 9) + 30 * math.exp(-((x - 880) / 170.0) ** 2) * r.uniform(.3, 1)
            pts += [(x, hz - hgt), (x + wd, hz - hgt)]; x += wd
        img = draw.paint(img, draw.raster([np.array(pts + [(W + 20, hz + 2)])], W, H), '#131c28')
        dots = [np.array([(px, py), (px + 2, py), (px + 2, py + 2), (px, py + 2)]) for px, py in zip(r.uniform(60, W - 60, 46), hz - r.uniform(3, 20, 46))]
        img = light(img, draw.raster(dots, W, H), '#e8c47c', 2.0)
    img = comp.over(img, comp.mask(draw.gradient(W, H, (0, hz), (0, H), *water), draw.rect(W, H, 0, hz, W, H)))
    if moon and road:
        sh.setup(W, H, 9000 + shimmer)
        img = light(img, draw.raster(sh.moonroad(moon[0], hz + 3, H - 4, w0=moon[2] * 1.1, w1=520, th0=1.4, th1=4.2), W, H), '#efe6cc', 1.6)
    return img

# ------------------------------------------------------------------ light
def light(img, matte, colour, k=5.0):
    """Paint something that gives off light: the colour, k times brighter than paper. The master makes it glow."""
    a = np.asarray(matte, np.float32)[..., None]
    out = img * (1 - a); out[..., :3] += core.col(colour) * k * a; out[..., 3:] += a
    return out

def sigil(img, x, y, s=56, lit=1.0):
    """The chop: a vermilion square with one lit window, low and to the right."""
    img = draw.paint(img, draw.rect(W, H, x, y, x + s, y + s), RED)
    return light(img, draw.rect(W, H, x + s * .56, y + s * .5, x + s * .79, y + s * .8), LAMP, 1.0 + 3.0 * lit)

# ------------------------------------------------------------------ lettering
_FONT = {}
def font(size, style='Open Sans Condensed:style=ExtraBold'):
    if (size, style) not in _FONT:
        f = subprocess.run(['fc-match', '-f', '%{file}', style], capture_output=True, text=True).stdout.strip()
        _FONT[(size, style)] = ImageFont.truetype(f, size)
    return _FONT[(size, style)]

def text(xy, string, size, track=0, anchor='l', style='Open Sans Condensed:style=ExtraBold'):
    """Lettering as a matte. anchor: 'l' left, 'm' centred, 'r' right (of xy[0]); xy[1] is the top. track = extra pixels between letters."""
    f = font(size, style); im = Image.new('L', (W, H), 0); d = ImageDraw.Draw(im)
    widths = [d.textlength(ch, font=f) + track for ch in string]
    x = xy[0] - (sum(widths) / 2 if anchor == 'm' else sum(widths) if anchor == 'r' else 0)
    for ch, wd in zip(string, widths):
        d.text((x, xy[1]), ch, fill=255, font=f); x += wd
    return np.asarray(im, np.float32) / 255

def write(img, xy, string, size, colour=INK, track=0, anchor='l', opacity=1.0, style='Open Sans Condensed:style=ExtraBold'):
    return draw.paint(img, text(xy, string, size, track, anchor, style), colour, opacity)

def name_card(img, name, t, side='l'):
    """The standard character card, lower third. t runs 0..1 over the card's life (it wipes in, holds, and stays).
    name is a key of CAST. Use this for every introduction so they match."""
    c = CAST[name]; x0 = 84 if side == 'l' else W - 84; sgn = 1 if side == 'l' else -1
    a = ease(clamp01(t / .22), 'out'); b = ease(clamp01((t - .10) / .25), 'out')
    bar = draw.rect(W, H, min(x0, x0 + sgn * 430 * a), 566, max(x0, x0 + sgn * 430 * a), 572)
    img = draw.paint(img, bar, RED)
    wipe = draw.rect(W, H, 0, 0, x0 + 700 * b, H) if side == 'l' else draw.rect(W, H, x0 - 700 * b, 0, W, H)
    anchor = 'l' if side == 'l' else 'r'
    img = draw.paint(img, text((x0, 458), c['title'], 96, track=7, anchor=anchor) * wipe, INK)
    img = draw.paint(img, text((x0 + sgn * 2, 584), c['role'].upper(), 28, track=6, anchor=anchor) * wipe, DIM)
    wx = x0 + sgn * 452 * a - (0 if side == 'l' else 20)
    return light(img, draw.rect(W, H, wx, 556, wx + 20, 582) * a, c['window'], 4.0)

