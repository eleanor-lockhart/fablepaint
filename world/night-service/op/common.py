"""NIGHT SERVICE opening: the shared kit. Every shot imports this so that all sequences match.
Do not edit this file while shots are in production; if you need something else, define it in your shot.

Grid: 1280 x 720, 12 poses a second (shot on twos), 120 beats a minute. One beat = 6 poses, one bar = 24 poses = 2 s.
A shot returns UNFINISHED frames: linear-light images in which anything that gives off light is simply very bright
(use light()). The master applies bloom, tone-mapping, vignette and grain to every frame the same way (finish()).
"""
