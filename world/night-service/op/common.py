_WALK = {}
_WALK_STYLE = dict(dee=dict(stride=.82, stance=.62, lift=.050, lean=3.0, arm=1.1, elbow=14.0),
                   marisol=dict(stride=.86, stance=.60, lift=.058, lean=2.0, arm=1.2, elbow=12.0),
                   red=dict(stride=.74, stance=.63, lift=.045, lean=2.0, arm=.6, elbow=10.0),
                   lang=dict(stride=.70, stance=.60, lift=.040, lean=0.0, arm=.35, elbow=16.0, strike_pitch=14.0),
                   passenger=dict(stride=.50, stance=.68, lift=.028, lean=6.0, arm=.25, elbow=10.0, strike_pitch=10.0, stance_knee=((0, 8), (.14, 16), (.40, 10), (.50, 12))))
def walker(name):
    """The character's own walk (a backlot.figure.Walk). walker(name).pose(g) gives the pose at phase g of a stride;
    .stride is how far (in the character's own heights) one full stride carries them. A stride of two steps per second
    (g advancing 1.0 every 12 poses) puts a foot down on every beat."""
    if name not in _WALK:
        _WALK[name] = _keeper.make()[1] if name == 'keeper' else fg.Walk(CAST[name]['fig'], **_WALK_STYLE[name])
    return _WALK[name]

def walk_pose(name, g, **over):
    """A walking pose with some joints overridden (e.g. Red's lantern arm held steady: shN=14, elN=10)."""
    p = dict(walker(name).pose(g)); p.update(over); return p

def figure(img, name, pose=None, x=640, ground=640, size=420, flip=False, window=True, glow=5.0, colours=None, edge=None):
    """Draw a member of the cast. pose=None is their standing pose. size = pixel height of a figure of stature 1.0
    (each character is scaled by their own height). ground = pixel y of the floor under them. flip faces them left."""
    c = CAST[name]
    img = fg.draw_figure(img, c['fig'], c['pose'] if pose is None else pose, size * c['height'], (x, ground), colours=colours or c.get('colours', FIG),
                         edge=edge or c.get('edge', EDGE), edge_w=1.5, flip=flip, window=c['window'] if window else None)
    if glow:
        img[..., :3] += img[..., :3] * fg.draw_figure.lit[..., None] * glow
    return img

